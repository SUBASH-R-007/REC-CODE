import { cppNodeDefs, cppReaderKit, cppType } from "./cpp";
import { comparedTypeOf, parseType, typeToString, type FunctionSignature } from "./signature";

/**
 * A complete, self-contained testlib checker for a CUSTOM_CHECKER FUNCTION
 * problem, with a TODO where the author writes the check. It reads values
 * with exactly the reader the C++ harness uses (cppReaderKit), so:
 *
 *   input.txt   the test's input — one JSON line per parameter;
 *   answer.txt  the jury's answer — one valid result (validated too: an
 *               invalid jury answer is a checker FAIL, never the student's);
 *   output.txt  the student's result, ALREADY decoded and re-serialised
 *               canonically by the judge (malformed output never reaches the
 *               checker — it is Wrong Answer before the checker runs).
 *
 * The file is the author's: no hidden prelude, nothing added at compile
 * time beyond testlib.h (the worker compiles it with -std=c++20 against the
 * pinned testlib toolchain). A value that does not parse is a checker FAIL.
 */
export function checkerTemplate(sig: FunctionSignature): string {
  const params = sig.params.map((p) => ({ name: p.name, type: parseType(p.type) }));
  const compared = comparedTypeOf(sig);
  const taken = new Set(params.map((p) => p.name));
  const free = (name: string) => (taken.has(name) ? `recx_${name}` : name);
  const candidate = free("candidate");
  const jury = free("jury");
  const got = free("got");
  const check = free("checkAnswer");
  const why = free("reason");

  // "T const&" binds a TreeNode* as well as a vector (a "const TreeNode*&" would not).
  const ref = (t: ReturnType<typeof parseType>) => `${cppType(t)} const&`;
  const checkParams = [...params.map((p) => `${ref(p.type)} ${p.name}`), `${ref(compared)} ${candidate}`].join(", ");
  const args = params.map((p) => p.name);
  const comparedName = typeToString(compared);
  const what = sig.comparator === "IN_PLACE_MUTATION" ? `the parameter ${sig.mutatedParam} after the call` : "the result";

  return [
    `// testlib checker for Solution.${sig.methodName}(${sig.params.map((p) => `${p.name}: ${p.type}`).join(", ")}) -> ${sig.returns}`,
    "// Comparator CUSTOM_CHECKER. Generated by checkerTemplate(); write the check where it says TODO.",
    "//",
    "//   input.txt   the test's input: one JSON line per parameter",
    `//   answer.txt  the jury's answer: one valid ${comparedName}`,
    `//   output.txt  the student's ${comparedName}, already decoded and re-serialised by the judge`,
    "//",
    "// Exit with quitf(_ok, ...) to accept, quitf(_wa, ...) to reject with a short reason,",
    "// quitf(_pc(n), ...) for n% partial credit, and quitf(_fail, ...) when the TEST itself is",
    "// wrong (for example an invalid jury answer) — a FAIL is the problem's bug, never the student's.",
    '#include "testlib.h"',
    "#include <bits/stdc++.h>",
    "using namespace std;",
    '#define RECX_HARNESS_FAIL(what) quitf(_fail, "malformed value (%s)", what)',
    ...cppNodeDefs(sig),
    cppReaderKit(sig),
    "/** One JSON line of `stream`, parsed with the judge's own reader. */",
    "template <class T> T readValue(InStream& stream) {",
    "    string line = stream.readLine();",
    "    T value{};",
    "    recx_harness::In in(line);",
    "    recx_harness::parse(in, value);",
    "    return value;",
    "}",
    "",
    `/** Why \`${candidate}\` is not a correct ${what} for this input, or "" when it is. */`,
    `string ${check}(${checkParams}) {`,
    `    // TODO: check ${candidate} against the input and return a short reason when it is wrong.`,
    `    return "the checker has not been written yet";`,
    "}",
    "",
    "int main(int argc, char* argv[]) {",
    "    registerTestlibCmd(argc, argv);",
    ...params.map((p) => `    ${cppType(p.type)} ${p.name} = readValue<${cppType(p.type)}>(::inf);`),
    `    ${cppType(compared)} ${jury} = readValue<${cppType(compared)}>(::ans);`,
    `    ${cppType(compared)} ${got} = readValue<${cppType(compared)}>(::ouf);`,
    "",
    `    string ${why} = ${check}(${[...args, jury].join(", ")});`,
    `    if (!${why}.empty()) quitf(_fail, "the jury answer is not valid: %s", ${why}.c_str());`,
    `    ${why} = ${check}(${[...args, got].join(", ")});`,
    `    if (!${why}.empty()) quitf(_wa, "%s", ${why}.c_str());`,
    '    quitf(_ok, "a valid answer");',
    "}",
    "",
  ].join("\n");
}
