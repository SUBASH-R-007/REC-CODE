/**
 * Create the SQL judge's sandbox cluster objects on a development machine
 * (Phase 12k), and write the two connection strings into the gitignored
 * apps/sql-judge/.env.local.
 *
 * What it makes, and why each line is there:
 *
 *   a database (recx_sql_sandbox)  holds nothing but per-submission schemas.
 *                                  The judge refuses to start if the
 *                                  database it is pointed at contains
 *                                  application tables, so this is the only
 *                                  place it will run.
 *   recx_sql_owner                 owns the schemas and runs the author's
 *                                  setup scripts. CREATE on the database,
 *                                  nothing else.
 *   recx_sql_student               runs the student's statement. NOINHERIT,
 *                                  member of nothing, no CREATE, no
 *                                  TEMPORARY, and no privilege on schema
 *                                  public — everything it may read is
 *                                  granted per case and dropped with the
 *                                  schema.
 *
 * The passwords are generated here and written only to .env.local. They are
 * piped to psql on stdin rather than passed as arguments, so they never
 * reach a process list, a shell history or a log.
 *
 * Usage (from the repository root, with the WSL2 stack up):
 *   node scripts/dev/sql-sandbox-up.mjs
 */
import { randomBytes } from "node:crypto";
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const ENV_FILE = path.resolve("apps/sql-judge/.env.local");
const DATABASE = "recx_sql_sandbox";
const OWNER = "recx_sql_owner";
const STUDENT = "recx_sql_student";
const PORT = 5433;

/** A password with no characters that need escaping in a URL or in SQL. */
const newPassword = () => randomBytes(24).toString("base64url");

function readExisting() {
  if (!existsSync(ENV_FILE)) return {};
  const found = {};
  for (const line of readFileSync(ENV_FILE, "utf8").split(/\r?\n/)) {
    const match = /^([A-Z_]+)=(.*)$/.exec(line.trim());
    if (match) found[match[1]] = match[2].replace(/^"|"$/g, "");
  }
  return found;
}

function passwordFrom(url) {
  const match = /^postgres(?:ql)?:\/\/[^:]+:([^@]+)@/.exec(url ?? "");
  return match ? decodeURIComponent(match[1]) : null;
}

function psql(sql, { database = "postgres" } = {}) {
  // stdin, so nothing secret is ever an argument.
  return execFileSync(
    "wsl",
    ["-d", "Ubuntu", "-u", "postgres", "--", "psql", "-v", "ON_ERROR_STOP=1", "-p", String(PORT), "-d", database, "-f", "-"],
    { input: sql, encoding: "utf8" },
  );
}

const existing = readExisting();
const ownerPassword = passwordFrom(existing.RECX_SQL_OWNER_URL) ?? newPassword();
const studentPassword = passwordFrom(existing.RECX_SQL_STUDENT_URL) ?? newPassword();

// Roles and the database. Everything is idempotent: running this twice
// resets the passwords to what .env.local already holds.
psql(`
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '${OWNER}') THEN
    CREATE ROLE ${OWNER} LOGIN;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '${STUDENT}') THEN
    CREATE ROLE ${STUDENT} LOGIN NOINHERIT;
  END IF;
END $$;
ALTER ROLE ${OWNER} WITH LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS PASSWORD '${ownerPassword}';
ALTER ROLE ${STUDENT} WITH LOGIN NOINHERIT NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS PASSWORD '${studentPassword}';
SELECT 'roles ready' AS step;
`);

const exists = psql(`SELECT 1 FROM pg_database WHERE datname = '${DATABASE}'`).includes("(1 row)");
if (!exists) psql(`CREATE DATABASE ${DATABASE} OWNER ${OWNER}`);

// Privileges inside the sandbox database. PUBLIC loses everything: a role
// that can connect is not a role that can create.
psql(
  `
REVOKE ALL ON DATABASE ${DATABASE} FROM PUBLIC;
GRANT CONNECT, CREATE, TEMPORARY ON DATABASE ${DATABASE} TO ${OWNER};
GRANT CONNECT ON DATABASE ${DATABASE} TO ${STUDENT};
REVOKE ALL ON SCHEMA public FROM PUBLIC;
GRANT ALL ON SCHEMA public TO ${OWNER};
SELECT 'privileges ready' AS step;
`,
  { database: DATABASE },
);

const ownerUrl = `postgresql://${OWNER}:${encodeURIComponent(ownerPassword)}@127.0.0.1:${PORT}/${DATABASE}`;
const studentUrl = `postgresql://${STUDENT}:${encodeURIComponent(studentPassword)}@127.0.0.1:${PORT}/${DATABASE}`;

const contents = `# Generated by scripts/dev/sql-sandbox-up.mjs. Development only; gitignored.
# The SQL judge holds these two and nothing else: no application DATABASE_URL,
# no AUTH_SECRET, no storage key. It refuses to start if one is present.
NODE_ENV=development
LOG_LEVEL=info
RECX_NODE_ID=${existing.RECX_NODE_ID ?? "sql-dev-1"}
RECX_NODE_TOKEN=${existing.RECX_NODE_TOKEN ?? randomBytes(24).toString("base64url")}
RECX_APP_URL=${existing.RECX_APP_URL ?? "http://127.0.0.1:3000"}
REDIS_URL=${existing.REDIS_URL ?? "redis://127.0.0.1:6379"}
RECX_SQL_OWNER_URL=${ownerUrl}
RECX_SQL_STUDENT_URL=${studentUrl}
RECX_SLOTS=${existing.RECX_SLOTS ?? "2"}
RECX_QUEUES=${existing.RECX_QUEUES ?? "judge-sql-practice,judge-sql-run"}
# A developer's cluster is not hardened to production's standard; the judge
# still refuses outright if the database holds application tables.
RECX_DEV_ALLOW_UNHARDENED_CLUSTER=1
`;
writeFileSync(ENV_FILE, contents, "utf8");

console.log(`[sql-sandbox] ${DATABASE} ready on 127.0.0.1:${PORT} with roles ${OWNER} and ${STUDENT}`);
console.log(`[sql-sandbox] wrote ${ENV_FILE} (gitignored; the passwords are only there)`);
